-- ICT371 QUESTION 8: TRANSPORT FLEET MAINTENANCE
-- Service due at 5,000 km since last service.

DROP VIEW IF EXISTS v_service_due CASCADE;
DROP TABLE IF EXISTS service_alerts, trips, vehicles CASCADE;

CREATE TABLE vehicles (
    vehicle_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration VARCHAR(30) NOT NULL UNIQUE,
    current_odometer NUMERIC(12,2) NOT NULL CHECK (current_odometer >= 0),
    last_service_odometer NUMERIC(12,2) NOT NULL CHECK (last_service_odometer >= 0),
    CHECK (last_service_odometer <= current_odometer)
);

CREATE TABLE trips (
    trip_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id INTEGER NOT NULL REFERENCES vehicles(vehicle_id),
    trip_on DATE NOT NULL,
    start_odometer NUMERIC(12,2) NOT NULL CHECK (start_odometer >= 0),
    end_odometer NUMERIC(12,2) NOT NULL CHECK (end_odometer > start_odometer)
);

CREATE TABLE service_alerts (
    vehicle_id INTEGER PRIMARY KEY REFERENCES vehicles(vehicle_id),
    km_since_service NUMERIC(12,2) NOT NULL,
    flagged_on DATE NOT NULL
);

-- (b) Is the vehicle due for service?
CREATE OR REPLACE FUNCTION fn_service_due(p_vehicle_id INTEGER)
RETURNS BOOLEAN LANGUAGE plpgsql AS $$
DECLARE v_current NUMERIC(12,2); v_last NUMERIC(12,2);
BEGIN
    SELECT current_odometer, last_service_odometer
    INTO v_current, v_last
    FROM vehicles WHERE vehicle_id = p_vehicle_id;

    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown vehicle ID: %', p_vehicle_id; END IF;
    RETURN (v_current - v_last) >= 5000;
END;
$$;

-- (d) Trigger checks start reading and updates vehicle odometer exactly once.
CREATE OR REPLACE FUNCTION fn_update_vehicle_odometer()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_current NUMERIC(12,2);
BEGIN
    SELECT current_odometer INTO v_current
    FROM vehicles WHERE vehicle_id = NEW.vehicle_id FOR UPDATE;

    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown vehicle ID: %', NEW.vehicle_id; END IF;
    IF NEW.end_odometer <= NEW.start_odometer THEN
        RAISE EXCEPTION 'End odometer must be greater than start odometer';
    END IF;
    IF NEW.start_odometer <> v_current THEN
        RAISE EXCEPTION 'Trip must start at current odometer value: %', v_current;
    END IF;

    UPDATE vehicles
    SET current_odometer = NEW.end_odometer
    WHERE vehicle_id = NEW.vehicle_id;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_trip_update_odometer
BEFORE INSERT ON trips
FOR EACH ROW EXECUTE FUNCTION fn_update_vehicle_odometer();

-- (c) Procedure inserts trip only; trigger updates vehicle odometer.
CREATE OR REPLACE PROCEDURE pr_record_trip(
    p_vehicle_id INTEGER, p_trip_on DATE, p_start NUMERIC, p_end NUMERIC
)
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM vehicles WHERE vehicle_id = p_vehicle_id) THEN
        RAISE EXCEPTION 'Unknown vehicle ID: %', p_vehicle_id;
    END IF;
    IF p_trip_on IS NULL OR p_start IS NULL OR p_end IS NULL OR p_end <= p_start THEN
        RAISE EXCEPTION 'Trip date and valid increasing odometer readings are required';
    END IF;

    INSERT INTO trips(vehicle_id, trip_on, start_odometer, end_odometer)
    VALUES (p_vehicle_id, p_trip_on, p_start, p_end);
END;
$$;

